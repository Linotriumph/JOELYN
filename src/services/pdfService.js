const fs = require('node:fs');
const path = require('node:path');
const PDFDocument = require('pdfkit');
const config = require('../config');

class PdfService {
  constructor(storageDir = config.storageDir) {
    this.storageDir = storageDir;
    if (!fs.existsSync(this.storageDir)) {
      fs.mkdirSync(this.storageDir, { recursive: true });
    }
  }

  /**
   * Generates a PDF report idempotently based on the job ID and payload.
   * If the PDF already exists, it detects the deterministic output and returns it.
   */
  async generateReport(jobId, payload = {}) {
    const filename = `report_${jobId}.pdf`;
    const outputPath = path.join(this.storageDir, filename);

    // Support simulated failure for testing failure & retry mechanics
    if (payload.forceFail || payload.simulateFailure) {
      throw new Error(`Simulated generation failure: Render engine faulted on report '${payload.title || 'Untitled'}'`);
    }

    // Work Idempotency check:
    // If output file already exists and is non-empty, work was already done (e.g. worker crashed before recording DB status)
    if (fs.existsSync(outputPath)) {
      const stats = fs.statSync(outputPath);
      if (stats.size > 0) {
        return {
          outputPath: path.relative(process.cwd(), outputPath),
          filename,
          fileSize: stats.size,
          idempotentReuse: true,
          generatedAt: new Date(stats.mtimeMs).toISOString(),
        };
      }
    }

    // Simulate genuine rendering workload if specified
    if (payload.renderDelayMs && payload.renderDelayMs > 0) {
      await new Promise((resolve) => setTimeout(resolve, payload.renderDelayMs));
    }

    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({ margin: 50, size: 'A4' });
        const writeStream = fs.createWriteStream(outputPath);

        doc.pipe(writeStream);

        // Header / Branding
        doc
          .fillColor('#1E293B')
          .fontSize(22)
          .text('JOELYN REPORTING SYSTEM', { align: 'left' });

        doc
          .fillColor('#64748B')
          .fontSize(10)
          .text(`Generated by JOELYN Background Worker • Job ID: ${jobId}`, { align: 'left' });

        doc.moveDown(1.5);
        doc.strokeColor('#E2E8F0').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
        doc.moveDown(1.5);

        // Report Title & Metadata
        const title = payload.title || 'System Execution & Activity Report';
        const department = payload.department || 'Operations';
        const requestedBy = payload.requestedBy || 'System User';

        doc.fillColor('#0F172A').fontSize(16).text(title);
        doc.moveDown(0.5);

        doc.fontSize(10).fillColor('#334155');
        doc.text(`Department: ${department}`);
        doc.text(`Requested By: ${requestedBy}`);
        doc.text(`Timestamp: ${new Date().toISOString()}`);
        doc.text(`Format: High-Resolution PDF Document`);
        doc.moveDown(1.5);

        // Report Details Section
        doc.fillColor('#0F172A').fontSize(12).text('Summary Overview', { underline: true });
        doc.moveDown(0.5);

        const description = payload.description || 'This document was compiled and rendered asynchronously in a dedicated worker process.';
        doc.fillColor('#475569').fontSize(10).text(description, { lineGap: 4 });
        doc.moveDown(1.5);

        // Data Table / Items
        doc.fillColor('#0F172A').fontSize(12).text('Report Breakdown', { underline: true });
        doc.moveDown(0.5);

        const items = payload.items || [
          { metric: 'Initial Ingestion', status: 'Verified', score: '100%' },
          { metric: 'Worker Queue Claim', status: 'Atomic', score: '100%' },
          { metric: 'Idempotency Validation', status: 'Enforced', score: 'Pass' },
          { metric: 'Document Synthesis', status: 'Completed', score: 'Valid' },
        ];

        let tableY = doc.y;
        doc.fillColor('#1E293B').fontSize(10);
        doc.text('Metric / Item', 50, tableY);
        doc.text('Status', 280, tableY);
        doc.text('Value', 450, tableY);

        doc.moveDown(0.5);
        tableY = doc.y;
        doc.strokeColor('#CBD5E1').lineWidth(0.5).moveTo(50, tableY).lineTo(545, tableY).stroke();
        doc.moveDown(0.5);

        items.forEach((item) => {
          tableY = doc.y;
          doc.fillColor('#334155').fontSize(9);
          doc.text(String(item.metric || 'Item'), 50, tableY);
          doc.text(String(item.status || 'Active'), 280, tableY);
          doc.text(String(item.score || item.value || '-'), 450, tableY);
          doc.moveDown(0.5);
        });

        doc.moveDown(2);
        doc.strokeColor('#E2E8F0').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
        doc.moveDown(1);

        // Footer
        doc
          .fillColor('#94A3B8')
          .fontSize(8)
          .text('JOELYN Enterprise Engineering • Distributed Task Verification', 50, 750, {
            align: 'center',
            width: 495,
          });

        doc.end();

        writeStream.on('finish', () => {
          const stats = fs.statSync(outputPath);
          resolve({
            outputPath: path.relative(process.cwd(), outputPath),
            filename,
            fileSize: stats.size,
            idempotentReuse: false,
            generatedAt: new Date().toISOString(),
          });
        });

        writeStream.on('error', (err) => {
          reject(err);
        });
      } catch (err) {
        reject(err);
      }
    });
  }
}

module.exports = new PdfService();
